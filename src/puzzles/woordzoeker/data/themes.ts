export function getTheme(id: string): Theme | undefined {
  return THEMES.find((theme) => theme.id === id);
}

export interface PickOptions {
  /** How many words to return (fewer if the theme has fewer that fit). */
  count: number;
  /** Maximum number of grid letters per word, e.g. the larger of grid width/height. */
  maxLength: number;
  rng: Rng;
}

/** Picks random words from a theme whose grid form fits within `maxLength` letters. */
export function pickThemeWords(theme: Theme, { count, maxLength, rng }: PickOptions): string[] {
  const fitting = theme.woorden.filter((word) => toGridLetters(word).length <= maxLength);
  return shuffle(fitting, rng).slice(0, Math.max(0, count));
}
